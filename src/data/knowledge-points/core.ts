export function filterCoreKnowledgePointIds(categoryId: CategoryId, ids: readonly string[]) {
  const coreIds = new Set(coreKnowledgePointIdsByCategory[categoryId]);

  return ids.filter((id) => coreIds.has(id));
}

export function filterCoreKnowledgePoints(
  categoryId: CategoryId,
  points: readonly GraphKnowledgePoint[],
): GraphKnowledgePoint[] {
  const coreIds = new Set(coreKnowledgePointIdsByCategory[categoryId]);

  return points
    .filter((point) => coreIds.has(point.id))
    .map((point) => ({
      ...point,
      prerequisites: point.prerequisites.filter((id) => coreIds.has(id)),
      related: point.related.filter((id) => coreIds.has(id)),
    }));
}
